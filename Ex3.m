% 1. Формування сигналу зі зміною частоти
% Перші 3 сек: f=1Hz, частота дискретизації 100Гц
t1 = 0:0.01:3; 
x1 = sin(2*pi*t1);

% Наступні 2 сек: f=2Hz (4pi), частота дискретизації 40Гц
% Починаємо з 3.025, щоб не дублювати точку t=3
t2 = 3.025:0.025:5; 
x2 = sin(4*pi*t2);

% Об'єднуємо в один сигнал та перетворюємо в cell array
x_total = [x1 x2];
X = con2seq(x_total); 

% Формуємо цільовий вихід y(t) = 3x(t-1) + 1
% Це означає затримку сигналу на 1 крок та лінійне перетворення
% Ми просто зміщуємо вхідний масив на один елемент
y_total = 3 * x_total + 1;
T = con2seq(y_total); 

% 2. Створення адаптивної лінійної мережі
% Почнемо з n=2 блоків затримки, швидкість навчання 0.001 для стабільності
net = linearlayer(1:2, 0.001); 

% 3. Підготовка даних та навчання
[Xs, Xi, Ai, Ts] = preparets(net, X, T); 
net.trainParam.epochs = 2000; % Даємо трохи більше часу
net.trainParam.goal = 1e-6;
net = train(net, Xs, Ts, Xi, Ai); 

% 4. Моделювання та побудова графіка помилки
Y = sim(net, Xs, Xi); 
Y_mat = cat(2, Y{:}); 
Ts_mat = cat(2, Ts{:});
error = Ts_mat - Y_mat;

figure;
plot(error, 'm', 'LineWidth', 1);
title('Графік помилки: зміна частоти та затримка (Експеримент 3)');
xlabel('Номер відліку');
ylabel('Помилка');
grid on;
% 1. Формування та дискретизація функції
f_sampling = 50; % Частота вимірювань (Гц) 
dt = 1 / f_sampling; % Крок дискретизації 
time = 0 : dt : 2.5; % Тривалість 2.5 сек 

x_val = sin(2 * pi * time); % Вхідний сигнал x(t) 
y_val = 2 * x_val + 3; % Цільове перетворення y(t) 

% Перетворення числових масивів у послідовності комірок (cell array)
X = con2seq(x_val); 
T = con2seq(y_val); 

% 2. Створення адаптивної лінійної мережі (затримка 2 блоки)
net = linearlayer(1:4, 0.001); 

% 3. Підготовка даних та навчання
[Xs, Xi, Ai, Ts] = preparets(net, X, T); % 
net.trainParam.epochs = 1000; % Максимальна кількість епох 
net.trainParam.goal = 1e-6; % Цільове значення помилки 
net = train(net, Xs, Ts, Xi, Ai); % Навчання мережі 

% 4. Моделювання та побудова графіка помилки
Y = sim(net, Xs, Xi); % Отримання виходу мережі 

% Перетворення результатів з cell array у звичайні матриці для розрахунків
Y_mat = cat(2, Y{:}); % [cite: 644]
Ts_mat = cat(2, Ts{:}); % [cite: 644]
error = Ts_mat - Y_mat; % Обчислення помилки 

figure;
plot(error, 'r', 'LineWidth', 1.5); % Графік помилки 
title('Графік помилки на виході мережі (Експеримент 2)');
xlabel('Номер відліку');
ylabel('Помилка');
grid on;
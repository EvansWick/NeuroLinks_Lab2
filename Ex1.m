% 1. Підготовка вхідних та цільових даних (послідовності)
X = {5 4 3 2}; % Вхідний сигнал
T = {10 20 30 40}; % Цільовий вихід

% 2. Створення адаптивної лінійної мережі
% inputDelays 1:2 означає лінію затримки з двох блоків
% Швидкість навчання за замовчуванням 0.01
net = linearlayer(1:3, 0.01); 

% 3. Підготовка даних з урахуванням затримок 
[Xs, Xi, Ai, Ts] = preparets(net, X, T);

% 4. Налаштування параметрів навчання 
net.trainParam.epochs = 1000; % Максимальна кількість епох 
net.trainParam.goal = 0.001;  % Цільова помилка

% 5. Навчання мережі 
net = train(net, Xs, Ts, Xi, Ai);

% 6. Тестування навченої мережі
Y = sim(net, Xs, Xi);

% Виведення результату
disp('Прогноз мережі:');
disp(Y);
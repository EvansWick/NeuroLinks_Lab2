% 1. Підготовка вхідних даних (X) та цільових значень (T) для XOR

X = [0 1 0 1; 0 0 1 1]; 
T = [0 1 1 0];          

% 2. Створення багатошарової мережі прямого поширення
% Прихований шар із 3 нейронами, функція навчання - 'trainlm'
net = feedforwardnet(3, 'trainlm');

% Налаштування параметрів
net.trainParam.epochs = 1000; 
net.trainParam.goal = 1e-5;    

% 3. Навчання мережі методом зворотного поширення помилки
net.divideFcn = '';
net = train(net, X, T);

% 4. Тестування навченої мережі
Y = sim(net, X);

% Відображення результатів (округлюємо для зручності читання)
disp('Вхідні комбінації:');
disp(X);
disp('Результат роботи нейромережі:');
disp(Y);
disp('Округлені логічні значення:');
disp(round(Y));

% Подаємо пару (0, 1) прямо в дужках
result = net([0; 0]);
result = round(result);
disp('0 xor 0 = ');
disp(result);